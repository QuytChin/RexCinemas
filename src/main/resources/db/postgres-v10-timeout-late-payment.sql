-- Non-destructive PostgreSQL migration for immutable checkout holds and late-payment reconciliation.
CREATE TABLE IF NOT EXISTS seat_hold_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
  user_id BIGINT NOT NULL REFERENCES app_users(id), showtime_id BIGINT NOT NULL REFERENCES showtimes(id),
  expires_at TIMESTAMP(3) NOT NULL, created_at TIMESTAMP(3) NOT NULL,
  CONSTRAINT uk_hold_session_user_showtime UNIQUE (user_id, showtime_id)
);
CREATE INDEX IF NOT EXISTS idx_hold_session_expires ON seat_hold_sessions(expires_at);
CREATE TABLE IF NOT EXISTS late_payment_cases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, version BIGINT NOT NULL DEFAULT 0,
  booking_id BIGINT NOT NULL REFERENCES bookings(id), provider_transaction_id VARCHAR(120) NOT NULL UNIQUE,
  payment_reference VARCHAR(120), amount NUMERIC(12,2) NOT NULL, bank_recorded_at TIMESTAMP(3),
  webhook_received_at TIMESTAMP(3), status VARCHAR(30) NOT NULL, reason VARCHAR(600), refunded_at TIMESTAMP(3),
  refunded_by VARCHAR(180), refunded_by_user_id BIGINT, refund_reference VARCHAR(120), refund_amount NUMERIC(12,2),
  refund_evidence VARCHAR(600), refund_note VARCHAR(255), refund_failed_at TIMESTAMP(3), refund_failure_reason VARCHAR(255),
  created_at TIMESTAMP(3) NOT NULL, updated_at TIMESTAMP(3) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_late_payment_status_created ON late_payment_cases(status, created_at);
CREATE INDEX IF NOT EXISTS idx_late_payment_booking ON late_payment_cases(booking_id);
CREATE TABLE IF NOT EXISTS late_payment_case_audits (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, late_payment_case_id BIGINT NOT NULL REFERENCES late_payment_cases(id),
  action VARCHAR(40) NOT NULL, actor VARCHAR(180), detail VARCHAR(600), created_at TIMESTAMP(3) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_late_payment_audit_case_created ON late_payment_case_audits(late_payment_case_id, created_at);
